#!/bin/bash
# VPS first-boot: generate /opt/avibe/.env with fresh secrets.
# Secrets never leave the server. Re-running OVERWRITES .env (destructive).
set -euo pipefail
cd /opt/avibe

# Alphanumeric only: safe for postgres DSN URLs and MinIO passwords.
gen_pw() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c 40; }
# Full base64: .env-safe values used as opaque HMAC/JWT/AES keys.
gen_b64() { openssl rand -base64 "$1" | tr -d '\n'; }

DB_PASSWORD=$(gen_pw)
MINIO_ROOT_PASSWORD=$(gen_pw)
JWT_ACCESS_SECRET=$(gen_b64 48)
JWT_REFRESH_SECRET=$(gen_b64 48)
HLS_SIGNING_KEY=$(gen_b64 48)
AES256_KEY_BASE64=$(gen_b64 32)

cat > .env <<EOF
# Generated by deploy/vps-init.sh on first boot. chmod 600. Never commit.
APP_ENV=prod
APP_ADDR=:8080

DB_NAME=avibe
DB_USER=avibe
DB_PASSWORD=${DB_PASSWORD}
DB_DSN=postgres://avibe:${DB_PASSWORD}@postgres:5432/avibe?sslmode=disable
REDIS_ADDR=redis:6379

JWT_ACCESS_SECRET=${JWT_ACCESS_SECRET}
JWT_REFRESH_SECRET=${JWT_REFRESH_SECRET}
HLS_SIGNING_KEY=${HLS_SIGNING_KEY}
AES256_KEY_BASE64=${AES256_KEY_BASE64}

MINIO_ROOT_USER=avibe-minio
MINIO_ROOT_PASSWORD=${MINIO_ROOT_PASSWORD}
# Server-side S3 calls stay on the private network; only URLs handed to
# browsers (presigned uploads, distributor links) use the public host (S-01).
S3_ENDPOINT=http://localstack:4566
S3_PUBLIC_ENDPOINT=https://hls.avibemusic.com
S3_REGION=us-east-1
S3_ACCESS_KEY=avibe-minio
S3_SECRET_KEY=${MINIO_ROOT_PASSWORD}
S3_USE_SSL=false
S3_STAGING_BUCKET=local-staging
S3_PUBLIC_HLS_BUCKET=local-hls
CDN_BASE_URL=https://avibemusic.com/local-hls

CORS_ALLOWED_ORIGINS=https://avibemusic.com
TRUSTED_PROXIES=172.30.0.0/16
FRONTEND_BASE_URL=https://avibemusic.com
OAUTH_REDIRECT_BASE_URL=https://avibemusic.com/api/v1/auth/oauth

SMTP_HOST=smtp.gmail.com
SMTP_PORT=587
SMTP_USER=
SMTP_PASS=
MAIL_FROM=no-reply@avibemusic.com
MAIL_FROM_NAME=AVIBE

TOSS_SECRET_KEY=
EOF
chmod 600 .env
echo "wrote /opt/avibe/.env (fill SMTP_USER/SMTP_PASS for password-reset mail)"
