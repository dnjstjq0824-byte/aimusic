#!/bin/bash
# VPS first-boot: generate /opt/avibe/.env with fresh secrets.
# Secrets never leave the server. Re-running never overwrites existing keys:
# it backs up .env and only fills in keys that are missing (R2 credentials
# added later, operator edits, and live secrets are all preserved).
set -euo pipefail
AVIBE_DIR="${AVIBE_DIR:-/opt/avibe}"
mkdir -p "$AVIBE_DIR"
cd "$AVIBE_DIR"

# Alphanumeric only: safe for postgres DSN URLs and MinIO passwords.
gen_pw() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c 40; }
# Full base64: .env-safe values used as opaque HMAC/JWT/AES keys.
gen_b64() { openssl rand -base64 "$1" | tr -d '\n'; }

DB_PASSWORD=$(gen_pw)
MINIO_ROOT_PASSWORD=$(gen_pw)
JWT_ACCESS_SECRET=$(gen_b64 48)
JWT_REFRESH_SECRET=$(gen_b64 48)
HLS_SIGNING_KEY=$(gen_b64 48)
AES256_KEY_BASE64=$(gen_b64 32)
NUXT_APP_SECRET=$(gen_b64 48)

# Postgres TLS (P1): self-signed server cert for sslmode=require clients.
# 999:999 is postgres in the official image (verified); the key must be
# owner-only or the server refuses to boot. Renew before expiry (825 days):
# re-run this block, then restart postgres from the compose file.
mkdir -p pgcerts
if [ ! -f pgcerts/server.crt ]; then
  openssl req -x509 -newkey rsa:2048 -keyout pgcerts/server.key -out pgcerts/server.crt \
    -days 825 -nodes -subj "/CN=postgres"
fi
chmod 644 pgcerts/server.crt
chmod 600 pgcerts/server.key
chown 999:999 pgcerts/server.key pgcerts/server.crt

TMP_NEW=$(mktemp)
cat > "$TMP_NEW" <<EOF
# Generated by deploy/vps-init.sh on first boot. chmod 600. Never commit.
APP_ENV=prod
APP_ADDR=:8080

DB_NAME=avibe
DB_USER=avibe
DB_PASSWORD=${DB_PASSWORD}
DB_DSN=postgres://avibe:${DB_PASSWORD}@postgres:5432/avibe?sslmode=require
REDIS_ADDR=redis:6379

JWT_ACCESS_SECRET=${JWT_ACCESS_SECRET}
JWT_REFRESH_SECRET=${JWT_REFRESH_SECRET}
HLS_SIGNING_KEY=${HLS_SIGNING_KEY}
AES256_KEY_BASE64=${AES256_KEY_BASE64}

# Media storage is private Cloudflare R2 (WI-D1). Fill R2 credentials via
# scripts/r2-env-append.ps1 (or leave empty; media calls fail closed until set).
STORAGE_DRIVER=r2
R2_ENDPOINT=https://ACCOUNT_ID.r2.cloudflarestorage.com
R2_ACCESS_KEY_ID=
R2_SECRET_ACCESS_KEY=
R2_STAGING_BUCKET=staging-private
R2_PUBLIC_HLS_BUCKET=public-hls
CDN_BASE_URL=https://avibemusic.com

MINIO_ROOT_USER=avibe-minio
MINIO_ROOT_PASSWORD=${MINIO_ROOT_PASSWORD}

CORS_ALLOWED_ORIGINS=https://avibemusic.com
TRUSTED_PROXIES=172.30.0.0/16
FRONTEND_BASE_URL=https://avibemusic.com
OAUTH_REDIRECT_BASE_URL=https://avibemusic.com/api/v1/auth/oauth

SMTP_HOST=smtp.gmail.com
SMTP_PORT=587
SMTP_USER=
SMTP_PASS=
MAIL_FROM=no-reply@avibemusic.com
MAIL_FROM_NAME=AVIBE

TOSS_SECRET_KEY=

NUXT_APP_SECRET=${NUXT_APP_SECRET}
EOF

if [ ! -f .env ]; then
  mv "$TMP_NEW" .env
  chmod 600 .env
  echo "wrote $AVIBE_DIR/.env (fill SMTP_USER/SMTP_PASS for password-reset mail; R2 creds via scripts/r2-env-append.ps1)"
else
  TS_BAK=$(date -u +%Y%m%d-%H%M%S)
  cp -p .env ".env.bak-vps-init-$TS_BAK"
  added=0
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in ''|'#'*) continue ;; esac
    key="${line%%=*}"
    if ! grep -q "^${key}=" .env; then
      printf '%s\n' "$line" >> .env
      added=$((added + 1))
    fi
  done < "$TMP_NEW"
  rm -f "$TMP_NEW"
  chmod 600 .env
  echo "kept existing .env (backup .env.bak-vps-init-$TS_BAK); added $added missing keys"
fi
